#!/usr/bin/env python3
"""Regenerate ``data/cc-pvdz.txt`` (cc-pVDZ for H–Ne) from Basis Set Exchange.

basis_set_exchange (BSD-3-Clause) is used as the data source only. Each
contraction vector becomes one shell, with its zero-coefficient primitives
dropped. Shells whose function type is ``gto_spherical`` are written with
flag 1 and use spherical harmonics (5 d functions per shell, not 6).

Format: ``@ <Z>`` starts an element, ``shell <l> <spherical 0|1>`` starts a
shell, and each following line is ``<exponent> <coefficient>``.

    python tools/gen_cc_pvdz.py data/cc-pvdz.txt
"""

import pathlib
import sys

import basis_set_exchange as bse

HEADER = """\
# cc-pVDZ basis set for H–Ar (Dunning), from Basis Set Exchange
# (https://www.basissetexchange.org). Generated by tools/gen_cc_pvdz.py; do not edit by hand.
#
# "@ <Z>" starts an element. "shell <l> <spherical>" starts a shell (spherical 1 =
# spherical harmonics, 0 = Cartesian). Each other line is "<exponent> <coefficient>".
"""


def main(out_path: str) -> None:
    basis = bse.get_basis("cc-pvdz", elements=list(range(1, 19)), fmt="json", header=False)
    if isinstance(basis, str):
        import json

        basis = json.loads(basis)
    lines = [HEADER.rstrip("\n")]
    for z in range(1, 19):
        element = basis["elements"][str(z)]
        lines.append(f"@ {z}")
        for shell in element["electron_shells"]:
            l = int(shell["angular_momentum"][0])
            spherical = 1 if shell["function_type"] == "gto_spherical" else 0
            exponents = [float(x) for x in shell["exponents"]]
            for coefficients in shell["coefficients"]:
                prims = [(e, float(c)) for e, c in zip(exponents, coefficients) if float(c) != 0.0]
                if not prims:
                    continue
                lines.append(f"shell {l} {spherical}")
                for e, c in prims:
                    lines.append(f"{e:.10e} {c:.12e}")
    pathlib.Path(out_path).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote cc-pVDZ for Z=1..18 to {out_path}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "data/cc-pvdz.txt")
