#!/usr/bin/env python3
"""Regenerate ``data/631g-na-ar.txt`` (6-31G for Na–Ar) from Basis Set Exchange.

The data come from the BSE REST API (https://www.basissetexchange.org), which
serves the Gaussian 09/GAMESS 6-31G contractions. Only the standard library
is used. Each contraction vector becomes one shell, with zero-coefficient
primitives dropped. A BSE "SP" shell (shared exponents) is split into an s
shell and a p shell, as the cc-pVDZ generator does.

Format: ``@ <Z>`` starts an element, ``shell <l> <spherical 0|1>`` starts a
shell, and each following line is ``<exponent> <coefficient>``.

    python tools/gen_631g_na_ar.py data/631g-na-ar.txt
"""

import json
import pathlib
import sys
import urllib.request

API = "https://www.basissetexchange.org/api/basis/6-31g/format/json/"
ELEMENTS = range(11, 19)  # Na..Ar

HEADER = """\
# 6-31G basis set for Na–Ar (Pople), from Basis Set Exchange
# (https://www.basissetexchange.org). Generated by tools/gen_631g_na_ar.py; do not edit by hand.
#
# "@ <Z>" starts an element. "shell <l> <spherical>" starts a shell (spherical 1 =
# spherical harmonics, 0 = Cartesian). Each other line is "<exponent> <coefficient>".
"""


def fetch():
    ids = ",".join(str(z) for z in ELEMENTS)
    with urllib.request.urlopen(f"{API}?elements={ids}", timeout=120) as resp:
        return json.load(resp)


def main(out_path):
    basis = fetch()
    lines = [HEADER.rstrip("\n")]
    for z in ELEMENTS:
        element = basis["elements"][str(z)]
        lines.append(f"@ {z}")
        for shell in element["electron_shells"]:
            spherical = 1 if shell["function_type"] == "gto_spherical" else 0
            exponents = [float(x) for x in shell["exponents"]]
            for l, coefficients in zip(shell["angular_momentum"], shell["coefficients"]):
                prims = [(e, float(c)) for e, c in zip(exponents, coefficients) if float(c) != 0.0]
                if not prims:
                    continue
                lines.append(f"shell {int(l)} {spherical}")
                for e, c in prims:
                    lines.append(f"{e:.10e} {c:.12e}")
    pathlib.Path(out_path).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote 6-31G for Z=11..18 to {out_path}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "data/631g-na-ar.txt")
