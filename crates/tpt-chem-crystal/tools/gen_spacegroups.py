#!/usr/bin/env python3
"""Regenerate ``data/spacegroups.txt`` from the spglib symmetry database.

spglib (BSD-3-Clause) is used here only as the data source; it is not a
dependency of the crate. For each of the 230 space-group numbers the first
Hall symbol in the database is taken, which is the standard setting for that
number. Each group's full set of operations (general positions, including the
identity) is written with integer rotations and translations in twelfths.

Run from anywhere with spglib installed:

    python tools/gen_spacegroups.py data/spacegroups.txt
"""

import pathlib
import sys

import spglib

HEADER = """\
# Space-group symmetry operations for the 230 space groups.
#
# Generated by tools/gen_spacegroups.py from the spglib symmetry database
# (spglib is BSD-3-Clause; it is a data source only). Do not edit by hand.
#
# A line "@ <number> <hall> <Hermann-Mauguin>" starts a group. Each following
# line is one operation: nine integers r11 r12 r13 r21 r22 r23 r31 r32 r33 for
# the rotation (row-major) and three integers t1 t2 t3 for the translation in
# twelfths, so x' = (R x + t / 12) acting on fractional coordinates.
"""


def main(out_path: str) -> None:
    lines = [HEADER.rstrip("\n")]
    seen = set()
    for hall in range(1, 531):
        spg_type = spglib.get_spacegroup_type(hall)
        if spg_type.number in seen:
            continue
        seen.add(spg_type.number)
        data = spglib.get_symmetry_from_database(hall)
        lines.append(f"@ {spg_type.number} {hall} {spg_type.international_short}")
        for rot, trans in zip(data["rotations"], data["translations"]):
            entries = [int(v) for v in rot.flatten()]
            for t in trans:
                twelfths = float(t) * 12.0
                rounded = round(twelfths)
                if abs(twelfths - rounded) > 1e-9:
                    raise ValueError(f"translation {t} is not a multiple of 1/12")
                entries.append(int(rounded))
            lines.append(" ".join(str(v) for v in entries))
    if len(seen) != 230:
        raise RuntimeError(f"expected 230 space-group numbers, found {len(seen)}")
    pathlib.Path(out_path).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(seen)} groups to {out_path}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "data/spacegroups.txt")
